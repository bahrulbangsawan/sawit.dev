//! Calls the MCP tools directly (no stdio) against a temp Sawit home.

mod canvas;
mod db;

fn text(result: &rmcp::model::CallToolResult) -> String {
    result
        .content
        .iter()
        .filter_map(|c| c.as_text().map(|t| t.text.clone()))
        .collect::<Vec<_>>()
        .join("\n")
}
