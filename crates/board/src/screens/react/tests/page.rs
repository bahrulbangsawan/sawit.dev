//! The page around the body: the file's shape, style sheets into the CSS, scripts left out,
//! assets listed and pointed at, and reading a screen's folder.

use std::path::PathBuf;

use super::{convert_page, inner};
use crate::screens::react::to_react;

#[test]
fn the_file_has_its_shape() {
    let page = r#"<!DOCTYPE html><html lang="en"><head><meta charset="utf-8"><title>T</title>
<base href="/"><style>p { color: red }</style></head><body>
<p>Hi</p>
</body></html>"#;
    let export = convert_page(page, &[]);
    assert_eq!(export.component, "Screen");
    assert_eq!(
        export.tsx,
        r#"// Generated by Sawit from the screen "Screen": a mechanical conversion of its HTML.
// The page's <html lang="en"> isn't part of a component: set it on your app's page.
import "./Screen.css";

export default function Screen() {
  return (
    <>
      <p>Hi</p>
    </>
  );
}
"#
    );
    assert_eq!(export.css, "p { color: red }\n");
    assert!(export.assets.is_empty());
}

#[test]
fn body_attributes_go_on_a_wrapping_div() {
    let export = convert_page(
        r#"<body class="dark" style="margin:0"><p>x</p></body>"#,
        &[],
    );
    assert!(
        export.tsx.contains(
            "    <div className=\"dark\" style={{ margin: \"0\" }}>\n      <p>x</p>\n    </div>\n"
        ),
        "{}",
        export.tsx
    );
    assert!(
        export.notes.iter().any(|n| n.contains("<body>")),
        "{:?}",
        export.notes
    );
}

#[test]
fn scripts_are_left_out_and_kept_at_the_end() {
    let page = r#"<html><head><script>
window.ready = true; /* a comment */
</script></head><body><p>x</p><script src="app.js" type="module"></script></body></html>"#;
    let export = convert_page(page, &[("app.js", b"x")]);
    assert_eq!(inner(&export.tsx), "<p>x</p>");
    assert!(
        export
            .notes
            .iter()
            .any(|n| n.contains("2 scripts were left out")),
        "{:?}",
        export.notes
    );
    let end = &export.tsx[export.tsx.find("/*\nLeft out").expect("the comment")..];
    assert_eq!(
        end,
        "/*\nLeft out of the component, to port by hand:\n\n<script>\nwindow.ready = true; /* \
         a comment *\\/\n</script>\n\n<script src=\"app.js\" type=\"module\"></script>\n*/\n"
    );
    assert!(export.assets.is_empty(), "a script isn't an asset");
}

#[test]
fn style_sheets_go_to_the_css_in_document_order() {
    let page = r#"<html><head>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Inter&display=swap">
<link rel="stylesheet" href="css/site.css">
<style>.head { color: red }</style>
<link rel="stylesheet" href="print.css" media="print">
<link rel="stylesheet" href="missing.css">
</head><body><style>.body { color: blue }</style><p>x</p>
<svg><style>.icon { fill: red }</style></svg></body></html>"#;
    let files: &[(&str, &[u8])] = &[
        ("css/site.css", b"@import \"base.css\";\n@import url(\"https://cdn.example/x.css\");\n.site { color: green }"),
        ("css/base.css", b".base { margin: 0 }"),
        ("print.css", b".print { display: none }"),
    ];
    let export = convert_page(page, files);
    assert_eq!(
        export.css,
        "@import url(\"https://fonts.googleapis.com/css2?family=Inter&display=swap\");\n\
         @import url(\"https://cdn.example/x.css\");\n\n\
         .base { margin: 0 }\n\n.site { color: green }\n\n.head { color: red }\n\n\
         @media print {\n.print { display: none }\n}\n\n.body { color: blue }\n\n.icon { fill: red }\n"
    );
    assert!(
        export
            .notes
            .iter()
            .any(|n| n.contains("Remote style sheets") && n.contains("fonts.googleapis.com")),
        "{:?}",
        export.notes
    );
    assert!(
        !export.tsx.contains("<style") && !export.tsx.contains("<link"),
        "{}",
        export.tsx
    );
}

#[test]
fn local_files_are_pointed_at_the_assets_and_listed_once() {
    let page = r##"<html><head><style>.a { background: url(img/bg.png) }</style>
<link rel="stylesheet" href="css/site.css"></head><body>
<img src="img/logo.png" srcset="img/logo.png 1x, img/logo@2x.png 2x, img/gone.png 3x" alt="">
<img src="https://cdn.example/x.png" alt=""><img src="data:image/png;base64,AAAA" alt="">
<img src="missing.png" alt=""><img src="img/my logo.png" alt="">
<div style="background-image: url(img/bg.png)"></div>
<svg><image href="img/logo.png"></image><use href="#local"></use></svg>
<a href="about.html">About</a>
</body></html>"##;
    let files: &[(&str, &[u8])] = &[
        ("css/site.css", b".b { background: url(../img/bg.png) } @font-face { src: url(fonts/x.woff2) format(\"woff2\") }"),
        ("css/fonts/x.woff2", b"font"),
        ("img/bg.png", b"png"),
        ("img/logo.png", b"png"),
        ("img/logo@2x.png", b"png"),
        ("img/my logo.png", b"png"),
        ("about.html", b"<p>about</p>"),
    ];
    let export = convert_page(page, files);
    let out = inner(&export.tsx);
    for expected in [
        r#"<img src="./Screen-assets/img/logo.png" srcSet="./Screen-assets/img/logo.png 1x, ./Screen-assets/img/logo@2x.png 2x, img/gone.png 3x" alt="" />"#,
        r#"<img src="https://cdn.example/x.png" alt="" />"#,
        r#"<img src="data:image/png;base64,AAAA" alt="" />"#,
        r#"<img src="missing.png" alt="" />"#,
        r#"<img src="./Screen-assets/img/my%20logo.png" alt="" />"#,
        r#"<div style={{ backgroundImage: "url(\"./Screen-assets/img/bg.png\")" }} />"#,
        r#"<image href="./Screen-assets/img/logo.png" />"#,
        r##"<use href="#local" />"##,
        r#"<a href="about.html">About</a>"#,
    ] {
        assert!(out.contains(expected), "{expected}\nin\n{out}");
    }
    assert!(
        export
            .css
            .contains(".a { background: url(\"./Screen-assets/img/bg.png\") }"),
        "{}",
        export.css
    );
    assert!(
        export
            .css
            .contains(".b { background: url(\"./Screen-assets/img/bg.png\") }"),
        "{}",
        export.css
    );
    assert!(
        export
            .css
            .contains("url(\"./Screen-assets/css/fonts/x.woff2\") format(\"woff2\")"),
        "{}",
        export.css
    );
    let listed: Vec<(&str, PathBuf)> = export
        .assets
        .iter()
        .map(|(to, from)| (to.as_str(), from.clone()))
        .collect();
    assert_eq!(
        listed,
        [
            ("Screen-assets/img/bg.png", PathBuf::from("img/bg.png")),
            (
                "Screen-assets/css/fonts/x.woff2",
                PathBuf::from("css/fonts/x.woff2")
            ),
            ("Screen-assets/img/logo.png", PathBuf::from("img/logo.png")),
            (
                "Screen-assets/img/logo@2x.png",
                PathBuf::from("img/logo@2x.png")
            ),
            (
                "Screen-assets/img/my logo.png",
                PathBuf::from("img/my logo.png")
            ),
        ]
    );
    let note = "Images and other files are in ./Screen-assets/ beside this file; <img src> paths \
                are relative to the page, so move them to your app's public folder or import them.";
    assert!(export.notes.iter().any(|n| n == note), "{:?}", export.notes);
}

#[test]
fn custom_elements_are_declared_for_typescript() {
    let page = r#"<body><my-card class="c" some-prop="1">x</my-card><my-card></my-card>
<svg><foreignObject><div xmlns="http://www.w3.org/1999/xhtml">in</div></foreignObject></svg></body>"#;
    let export = convert_page(page, &[]);
    assert!(
        export
            .tsx
            .contains(r#"<my-card className="c" some-prop="1">x</my-card>"#),
        "{}",
        export.tsx
    );
    assert!(export.tsx.contains("<div>in</div>"), "{}", export.tsx);
    assert!(
        export.tsx.ends_with(
            "}\n\n// The page's custom elements, for TypeScript; they render as written, and work \
             once their definitions load.\ndeclare module \"react\" {\n  namespace JSX {\n    \
             interface IntrinsicElements {\n      \"my-card\": Record<string, unknown>;\n    }\n  \
             }\n}\n"
        ),
        "{}",
        export.tsx
    );
    assert!(!export.tsx.contains("CSSProperties"), "{}", export.tsx);
}

#[test]
fn to_react_reads_the_screens_folder() {
    let dir = tempfile::tempdir().expect("a temp dir");
    std::fs::create_dir_all(dir.path().join("img")).expect("img");
    std::fs::write(
        dir.path().join("index.html"),
        r#"<img src="img/a.png" alt="A">"#,
    )
    .expect("page");
    std::fs::write(dir.path().join("img/a.png"), b"png").expect("png");
    let export = to_react(dir.path(), "Pricing", "Pricing.css", "Pricing-assets").expect("export");
    assert!(
        export.tsx.contains("export default function Pricing() {"),
        "{}",
        export.tsx
    );
    assert!(
        export.tsx.contains("import \"./Pricing.css\";"),
        "{}",
        export.tsx
    );
    assert!(
        export
            .tsx
            .contains(r#"<img src="./Pricing-assets/img/a.png" alt="A" />"#)
    );
    assert_eq!(
        export.assets,
        [(
            "Pricing-assets/img/a.png".to_string(),
            dir.path().join("img/a.png")
        )]
    );
    let empty = tempfile::tempdir().expect("a temp dir");
    assert!(to_react(empty.path(), "X", "X.css", "X-assets").is_err());
}
